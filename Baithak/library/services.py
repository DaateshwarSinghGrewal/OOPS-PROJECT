"""Business rules live here so views stay thin and operations are reusable."""
import math
from datetime import timedelta

from django.db import IntegrityError, transaction
from django.utils import timezone

from .models import (Attendance, BreakRecord, LocationEvent, Notification,
                     Reservation, ReservationPolicy, Seat, Student)


class BaithakError(Exception):
    """Expected domain error safe to show to a student."""


class SeatUnavailable(BaithakError):
    pass


class ReservationManager:
    def reserve(self, student, seat_id, duration_minutes):
        policy = ReservationPolicy.current()
        if not policy.accepts_duration(duration_minutes):
            raise BaithakError("Choose a duration within the library's allowed range.")
        now = timezone.now()
        try:
            with transaction.atomic():
                student = Student.objects.select_for_update().get(pk=student.pk)
                seat = Seat.objects.select_for_update().get(pk=seat_id)
                self.expire_due()
                if Reservation.objects.filter(student=student, status__in=Reservation.ACTIVE_STATUSES).exists():
                    raise BaithakError("You already have an active reservation.")
                if Reservation.objects.filter(seat=seat, status__in=Reservation.ACTIVE_STATUSES).exists():
                    raise SeatUnavailable("That seat was just reserved. Please choose another.")
                reservation = Reservation.objects.create(
                    student=student, seat=seat,
                    duration_minutes=duration_minutes,
                    checkin_deadline=now + timedelta(minutes=policy.checkin_grace_minutes),
                )
                NotificationManager().send(student, "Seat reserved. Your study timer starts when your library check-in is verified.", "reservation")
                return reservation
        except IntegrityError as exc:
            raise SeatUnavailable("That seat or your account already has an active reservation.") from exc

    def renew(self, student, duration_minutes):
        with transaction.atomic():
            renewable_statuses = [Reservation.Status.ACTIVE, Reservation.Status.BREAK, Reservation.Status.AWAY]
            reservation = Reservation.objects.select_for_update().filter(student=student, status__in=renewable_statuses).first()
            if not reservation or not reservation.ends_at or reservation.ends_at <= timezone.now():
                raise BaithakError("There is no active reservation to renew.")
            policy = ReservationPolicy.current()
            if not policy.accepts_duration(duration_minutes):
                raise BaithakError("Choose a duration within the library's allowed range.")
            reservation.ends_at = max(reservation.ends_at, timezone.now()) + timedelta(minutes=duration_minutes)
            reservation.duration_minutes += duration_minutes
            reservation.save(update_fields=["ends_at", "duration_minutes"])
            NotificationManager().send(student, "Your reservation was renewed successfully.", "renewal")
            return reservation

    def release(self, reservation, status=Reservation.Status.RELEASED):
        reservation.status = status
        reservation.checked_out_at = timezone.now()
        reservation.save(update_fields=["status", "checked_out_at"])
        return reservation

    def expire_due(self):
        now = timezone.now()
        # One warning per reservation, generated by server time (never a browser timer).
        for item in Reservation.objects.filter(status__in=Reservation.ACTIVE_STATUSES, ends_at__gt=now, ends_at__lte=now + timedelta(minutes=15)).select_related("student", "seat"):
            text = f"Your reservation for seat {item.seat.number} ends within 15 minutes."
            if not Notification.objects.filter(student=item.student, kind="expiry_warning", message=text, created_at__gte=item.ends_at - timedelta(minutes=15)).exists():
                NotificationManager().send(item.student, text, "expiry_warning")
        # Atomic per record; all release decisions use server time.
        for reservation in Reservation.objects.filter(status__in=Reservation.ACTIVE_STATUSES, ends_at__lte=now).select_related("student", "seat"):
            with transaction.atomic():
                item = Reservation.objects.select_for_update().get(pk=reservation.pk)
                if item.status not in Reservation.ACTIVE_STATUSES or item.ends_at > now:
                    continue
                item.status = Reservation.Status.EXPIRED
                item.checked_out_at = now
                item.save(update_fields=["status", "checked_out_at"])
                NotificationManager().send(item.student, f"Your reservation for seat {item.seat.number} has expired and the seat is available.", "release")
        # Reservations not checked in by the separate check-in deadline are released.
        for reservation in Reservation.objects.filter(status=Reservation.Status.RESERVED, checked_in_at__isnull=True, checkin_deadline__lte=now).select_related("student", "seat"):
            with transaction.atomic():
                item = Reservation.objects.select_for_update().get(pk=reservation.pk)
                if item.status == Reservation.Status.RESERVED and item.checkin_deadline <= now:
                    item.status = Reservation.Status.EXPIRED
                    item.checked_out_at = now
                    item.save(update_fields=["status", "checked_out_at"])
                    NotificationManager().send(item.student, f"Check-in window ended. Seat {item.seat.number} was released.", "release")
        BreakManager().expire_due()
        # Release location-away seats even when the browser has been closed.
        policy = ReservationPolicy.current()
        for item in Reservation.objects.filter(status=Reservation.Status.AWAY).select_related("student", "seat"):
            event = item.location_events.filter(returned_at__isnull=True).order_by("-recorded_at").first()
            if event and event.recorded_at + timedelta(minutes=policy.return_countdown_minutes) <= now:
                with transaction.atomic():
                    locked = Reservation.objects.select_for_update().get(pk=item.pk)
                    if locked.status == Reservation.Status.AWAY:
                        self.release(locked)
                        NotificationManager().send(locked.student, f"Seat {locked.seat.number} released after the location return countdown.", "release")


class NotificationManager:
    def send(self, student, message, kind="info"):
        return Notification.objects.create(student=student, message=message, kind=kind)

    def unread(self, student):
        return student.notifications.filter(read_at__isnull=True)


class AttendanceManager:
    def check_in_from_qr(self, token):
        import uuid
        try:
            token = uuid.UUID(str(token))
        except (TypeError, ValueError, AttributeError) as exc:
            raise BaithakError("This check-in QR code is invalid.") from exc
        reservation = Reservation.objects.filter(qr_token=token).select_related("student").first()
        if not reservation:
            raise BaithakError("This check-in QR code is invalid.")
        return self.check_in(reservation.student, token)

    def check_in(self, student, token):
        import uuid
        try:
            token = uuid.UUID(str(token))
        except (TypeError, ValueError, AttributeError) as exc:
            raise BaithakError("This check-in QR code is invalid.") from exc
        with transaction.atomic():
            reservation = Reservation.objects.select_for_update().select_related("seat").filter(student=student, qr_token=token).first()
            now = timezone.now()
            if not reservation or reservation.status != Reservation.Status.RESERVED:
                raise BaithakError("This QR code is invalid, expired, or already used.")
            if reservation.checkin_deadline <= now:
                raise BaithakError("The reservation's check-in window has expired.")
            if reservation.qr_used_at:
                raise BaithakError("This check-in QR code has already been used.")
            reservation.checked_in_at = now
            reservation.study_started_at = now
            reservation.ends_at = now + timedelta(minutes=reservation.duration_minutes)
            reservation.qr_used_at = now
            reservation.status = Reservation.Status.ACTIVE
            reservation.save(update_fields=["checked_in_at", "study_started_at", "ends_at", "qr_used_at", "status"])
            Attendance.objects.create(reservation=reservation, checked_in_at=now)
            NotificationManager().send(student, "Library check-in successful.", "checkin")
            return reservation

    def checkout(self, student):
        with transaction.atomic():
            reservation = Reservation.objects.select_for_update().filter(student=student, status__in=Reservation.ACTIVE_STATUSES).first()
            if not reservation:
                raise BaithakError("You do not have an active reservation.")
            reservation = ReservationManager().release(reservation, Reservation.Status.COMPLETED)
            Attendance.objects.filter(reservation=reservation, checked_out_at__isnull=True).update(checked_out_at=reservation.checked_out_at)
            NotificationManager().send(student, f"Seat {reservation.seat.number} checked out and released.", "release")
            return reservation


class BreakManager:
    def start(self, student, minutes):
        policy = ReservationPolicy.current()
        if minutes < 1 or minutes > min(30, policy.break_max_minutes):
            raise BaithakError("A break can be at most 30 minutes.")
        with transaction.atomic():
            reservation = Reservation.objects.select_for_update().filter(student=student, status=Reservation.Status.ACTIVE).first()
            if not reservation:
                raise BaithakError("Check in before starting a break.")
            now = timezone.now()
            item = BreakRecord.objects.create(reservation=reservation, expires_at=now + timedelta(minutes=minutes))
            reservation.status = Reservation.Status.BREAK
            reservation.save(update_fields=["status"])
            return item

    def return_from_break(self, student):
        with transaction.atomic():
            reservation = Reservation.objects.select_for_update().filter(student=student, status=Reservation.Status.BREAK).first()
            if not reservation:
                raise BaithakError("There is no active break to return from.")
            item = reservation.breaks.filter(returned_at__isnull=True).order_by("-started_at").first()
            if not item or item.expires_at <= timezone.now():
                raise BaithakError("Your break has expired and the seat has been released.")
            item.returned_at = timezone.now()
            item.save(update_fields=["returned_at"])
            reservation.status = Reservation.Status.ACTIVE
            reservation.save(update_fields=["status"])
            return reservation

    def expire_due(self):
        now = timezone.now()
        for item in BreakRecord.objects.filter(returned_at__isnull=True, expires_at__gt=now, expires_at__lte=now + timedelta(minutes=5)).select_related("reservation__student", "reservation__seat"):
            text = f"Your break from seat {item.reservation.seat.number} ends within 5 minutes. Return now to keep your seat."
            if not Notification.objects.filter(student=item.reservation.student, kind="break_warning", message=text, created_at__gte=item.expires_at - timedelta(minutes=5)).exists():
                NotificationManager().send(item.reservation.student, text, "break_warning")
        for item in BreakRecord.objects.filter(returned_at__isnull=True, expires_at__lte=now).select_related("reservation__student", "reservation__seat"):
            with transaction.atomic():
                current = BreakRecord.objects.select_for_update().get(pk=item.pk)
                if current.returned_at or current.expires_at > now:
                    continue
                current.returned_at = now
                current.save(update_fields=["returned_at"])
                reservation = Reservation.objects.select_for_update().get(pk=current.reservation_id)
                if reservation.status == Reservation.Status.BREAK:
                    ReservationManager().release(reservation)
                    NotificationManager().send(reservation.student, f"Break expired. Seat {reservation.seat.number} was released.", "release")


class LocationMonitor:
    """Distance alerts begin only from browser permission-backed location reports."""
    @staticmethod
    def distance_m(lat1, lon1, lat2, lon2):
        radius = 6371000
        p1, p2 = math.radians(lat1), math.radians(lat2)
        dp = math.radians(lat2-lat1)
        dl = math.radians(lon2-lon1)
        a = math.sin(dp/2)**2 + math.cos(p1)*math.cos(p2)*math.sin(dl/2)**2
        return 2 * radius * math.atan2(math.sqrt(a), math.sqrt(1-a))

    def report(self, student, latitude, longitude):
        policy = ReservationPolicy.current()
        with transaction.atomic():
            reservation = Reservation.objects.select_for_update().filter(student=student, status__in=[Reservation.Status.ACTIVE, Reservation.Status.AWAY]).first()
            if not reservation:
                raise BaithakError("Check in to a reservation before sending location updates.")
            distance = self.distance_m(latitude, longitude, policy.library_latitude, policy.library_longitude)
            event = reservation.location_events.filter(returned_at__isnull=True).order_by("-recorded_at").first()
            if distance > policy.permitted_radius_m:
                if reservation.status != Reservation.Status.AWAY:
                    reservation.status = Reservation.Status.AWAY
                    reservation.save(update_fields=["status"])
                    event = LocationEvent.objects.create(reservation=reservation, latitude=latitude, longitude=longitude, distance_m=distance)
                    NotificationManager().send(student, f"You appear to be outside the library area. Return within {policy.return_countdown_minutes} minutes or your seat will be released.", "location")
                elif event and event.recorded_at + timedelta(minutes=policy.return_countdown_minutes) <= timezone.now():
                    ReservationManager().release(reservation)
                    NotificationManager().send(student, f"Seat {reservation.seat.number} released after the location return countdown.", "release")
            elif reservation.status == Reservation.Status.AWAY:
                reservation.status = Reservation.Status.ACTIVE
                reservation.save(update_fields=["status"])
                if event:
                    event.returned_at = timezone.now()
                    event.save(update_fields=["returned_at"])
                NotificationManager().send(student, "Welcome back. Your seat is still reserved.", "location")
            return {"distance_m": round(distance), "status": reservation.status, "return_minutes": policy.return_countdown_minutes}


class SeatManager:
    FLOOR_COUNTS = ((Seat.Floor.GROUND, 184), (Seat.Floor.FIRST, 86), (Seat.Floor.SECOND, 60), (Seat.Floor.THIRD, 54), (Seat.Floor.FOURTH, 66))

    def seed(self):
        created = 0
        for floor, count in self.FLOOR_COUNTS:
            for number in range(1, count + 1):
                _, was_created = Seat.objects.get_or_create(floor=floor, number=number)
                created += int(was_created)
        return created

    def availability(self):
        ReservationManager().expire_due()
        reserved_ids = Reservation.objects.filter(status__in=Reservation.ACTIVE_STATUSES).values_list("seat_id", flat=True)
        return Seat.objects.exclude(pk__in=reserved_ids)
